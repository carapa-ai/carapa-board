#!/usr/bin/env bash
set -euo pipefail

BOARD_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLAYWRIGHT_ROOT="${PLAYWRIGHT_ROOT:-$BOARD_ROOT/../carapa-playwright}"
PLAYWRIGHT_SOURCE_REPO="https://github.com/carapa-ai/playwright"
PLAYWRIGHT_CORE="$PLAYWRIGHT_ROOT/packages/playwright-core"
DASHBOARD_ROOT="$PLAYWRIGHT_ROOT/packages/dashboard"
VITE_BIN="$PLAYWRIGHT_ROOT/node_modules/.bin/vite"
BROWSER_RUNTIME_DIR="${BROWSER_RUNTIME_DIR:-$BOARD_ROOT/../carapa-box/stacks/carapa-bot/bin}"
BROWSER_VIEWER_DIR="${BROWSER_VIEWER_DIR:-$BOARD_ROOT/ui/public/browser-viewer}"
case "$BROWSER_VIEWER_DIR" in
  /*) ;;
  *) BROWSER_VIEWER_DIR="$BOARD_ROOT/$BROWSER_VIEWER_DIR" ;;
esac
export BROWSER_VIEWER_DIR

usage() {
  cat >&2 <<'EOF'
Usage: scripts/build-browser-viewer.sh [--install]

Build the dashboard and shared dropdown renderer from the sibling Playwright
checkout. Publish the UI to BROWSER_VIEWER_DIR (default: ui/public/browser-viewer/)
and the renderer to BROWSER_RUNTIME_DIR (default: ../carapa-box/stacks/carapa-bot/bin).
Set PLAYWRIGHT_ROOT to use another checkout. Reattach the Browser viewer to load
the renderer from its mounted stack directory; no harness rebuild is required.
--install runs `npm ci --ignore-scripts` if the checkout has no Vite binary.
EOF
}

install_dependencies=false
case "${1:-}" in
  '') ;;
  --install) install_dependencies=true ;;
  --help|-h) usage; exit 0 ;;
  *) usage; exit 2 ;;
esac

if [[ ! -d "$DASHBOARD_ROOT" || ! -d "$PLAYWRIGHT_CORE" ]]; then
  echo "Playwright checkout not found: $PLAYWRIGHT_ROOT" >&2
  exit 1
fi

if [[ ! -d "$BROWSER_RUNTIME_DIR" ]]; then
  echo "Browser runtime directory not found: $BROWSER_RUNTIME_DIR" >&2
  exit 1
fi

if [[ ! -x "$VITE_BIN" ]]; then
  if [[ "$install_dependencies" != true ]]; then
    echo "Vite is not installed in $PLAYWRIGHT_ROOT." >&2
    echo "Run: (cd \"$PLAYWRIGHT_ROOT\" && npm ci --ignore-scripts)" >&2
    echo "Or rerun this script with --install." >&2
    exit 1
  fi
  (cd "$PLAYWRIGHT_ROOT" && npm ci --ignore-scripts)
fi

PLAYWRIGHT_SOURCE_COMMIT="$(git -C "$PLAYWRIGHT_ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
export PLAYWRIGHT_SOURCE_REPO PLAYWRIGHT_SOURCE_COMMIT

version="$(node -e 'const fs = require("node:fs"); const file = process.argv[1]; process.stdout.write(JSON.parse(fs.readFileSync(file, "utf8")).version);' "$PLAYWRIGHT_CORE/package.json")"
node - "$PLAYWRIGHT_ROOT" "$BROWSER_RUNTIME_DIR/browser-select-menu.cjs" <<'NODE'
const path = require('node:path');
const fs = require('node:fs');
const { createHash } = require('node:crypto');
const [root, output] = process.argv.slice(2);
const { PLAYWRIGHT_SOURCE_REPO: repo, PLAYWRIGHT_SOURCE_COMMIT: commit } = process.env;
const source = path.join(root, 'packages/playwright-core/src/tools/dashboard/selectMenu.ts');
const hash = createHash('sha256').update(fs.readFileSync(source)).digest('hex');
const { buildSync } = require(path.join(root, 'node_modules/esbuild'));
buildSync({
  entryPoints: [source], platform: 'node', format: 'cjs', target: 'node22',
  outfile: output,
  banner: { js: '// Generated by carapa-board/scripts/build-browser-viewer.sh; do not edit.\n// Source: carapa-playwright/packages/playwright-core/src/tools/dashboard/selectMenu.ts\n// Repository: ' + repo + '\n// Commit: ' + commit + '\n// License: Apache-2.0\n// SHA256: ' + hash },
});
console.log('Published browser dropdown runtime to ' + output);
NODE
echo "Building Playwright dashboard $version from $DASHBOARD_ROOT"

# packages/dashboard/vite.config.ts writes directly to
# packages/playwright-core/lib/vite/dashboard. This avoids the Playwright root
# build, which also builds the recorder, trace viewer and HTML reporter.
(
  cd "$DASHBOARD_ROOT"
  exec "$VITE_BIN" build --clearScreen=false
)

python3 "$BOARD_ROOT/scripts/vendor-browser-viewer.py" "$PLAYWRIGHT_CORE" "$version"
echo "Published browser viewer $version to $BROWSER_VIEWER_DIR"
